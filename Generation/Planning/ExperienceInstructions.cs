using System;
using GameMockStudio.Brief.Planning;

namespace GameMockStudio.Generation.Planning;

/// <summary>種類ごとの価値の一巡と検証方法を生成指示へ提供する。</summary>
public sealed class ExperienceInstructions
{
    /// <summary>画面の羅列に終わらない、対象ごとの実装要件を返す。</summary>
    public string ForKind(MockKind kind)
    {
        return kind switch
        {
            MockKind.Game => """
                ## ゲームの体験
                - 実際に遊べるゲーム本体を実装する。操作・目的・成功/失敗・再挑戦の一周を成立させる。
                - ジャンルは最大3種類。入力が空なら1〜3種類を選ぶ。指定された集合に勝手に追加しない。
                - 戦闘、物語、課金、オンライン機能を無関係な題材へ無理に足さない。
                """,
            MockKind.Service => """
                ## サービスの体験
                - 非ゲームのサービスモックを実装する。誰の、どの場面の困りごとをどう変えるかを一つに絞る。
                - 実際に入力→操作→結果→編集・取消を一巡できるようにする。主要ボタンは状態を変化させる。
                - 説明ページ、静止画、ダミーボタンの羅列だけで完了にしない。空の状態・入力不備・やり直しも実装する。
                - ゲームの勝敗・リトライ・ジャンルをサービスへ要求しない。Genresは空配列にする。
                - SNSは交流が中心の企画の場合だけ実装する。その場合は投稿、一覧、反応、公開範囲、非表示・デモ通報を小さく一巡させる。
                - 個人用や業務用の道具に、指定と無関係なフィード・フォロー・ポイントを追加しない。
                - 架空のデータだけを使う。ログイン、決済、投稿送信、通知送信、AI判定や外部連携はローカルの仮動作として「デモ」と表示する。
                - 実アカウント・個人情報を要求しない。ローカル保存を使う場合はサンプルを初期化できるようにする。
                - experiment.mdを新しく作り、仮説、対象者と利用場面、試す操作、観察指標、利用後の質問、見直す条件、次に決めることを記す。
                - 効果は未検証の仮説として記す。実際に測っていない効果や利用者の声を実績として書かない。
                """,
            MockKind.Gamification => """
                ## ゲーミフィケーションの体験
                - 対象領域の具体的な一場面と、変えたい現実の行動を一つに絞ったゲームモックを実装する。
                - 行動の入力→ゲームへの反映→意味のある選択→次の行動の一周を、実際に操作できるようにする。
                - 点数・バッジの表示だけで終えず、行動の内容がゲームの状態や選択肢にどう反映されるかを見せる。
                - 同じ中心行動をゲームなしでも行える通常モードを設け、切り替えて比較できるようにする。比較のため両モードに同じデモデータを使う。
                - ゲームの成功/失敗と、現実側の価値を区別する。遊びの再挑戦、行動の編集・取消、デモの初期化を用意する。
                - ジャンルは最大3種類。入力が空なら1〜3種類を選ぶ。指定された集合に勝手に追加しない。
                - 休むと資産を失う仕組みや強制的な連続利用を追加しない。ゲーム要素・演出・通知は利用者が選べるようにする。
                - 実世界の行動や学習履歴は架空のデモ入力で再現し、実アカウント・位置情報・外部送信・実決済を使わない。
                - experiment.mdを新しく作る。領域、対象の場面、行動を妨げる原因、行動とゲームの対応表、効果の仮説を書く。
                - 検証メモには通常モードとの比較手順、行動と体験の観察指標、負担や目的のずれ、見直す条件、利用後の質問、次に決めることも含める。
                - 効果や定着率を検証済みとして断定しない。実際に観察した事実と今後の仮説を分ける。
                """,
            _ => throw new InvalidOperationException("企画の種類が不正です。")
        };
    }
}
